package io.github.slavikjunior.syncclip.feature.sync.impl.domain.model

/**
 * Состояние соединения с relay-сервером (FR-2.3).
 *
 * Живёт в домене, а не рядом с транспортом: его показывает экран синхронизации,
 * то есть это часть контракта фичи, а не деталь реализации WebSocket. Слой
 * `presentation` не имеет права импортировать `data` (INV-10), поэтому
 * состояние вынесено сюда.
 */
internal enum class SyncConnectionStatus {

    /** Мастер-пароль не введён — шифровать нечем. */
    LOCKED,

    /** Соединения нет, идёт переподключение. */
    OFFLINE,

    /** WebSocket открыт. */
    ONLINE,

    /** Пять неудачных попыток подряд: показываем пользователю предупреждение. */
    SUSPENDED,
}
