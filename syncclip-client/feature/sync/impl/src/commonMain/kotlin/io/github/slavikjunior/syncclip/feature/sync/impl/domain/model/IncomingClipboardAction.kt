package io.github.slavikjunior.syncclip.feature.sync.impl.domain.model

/**
 * Что делать с входящим пакетом (FR-2.8, FR-2.11).
 *
 * Пакет всегда попадает в локальную историю, если не отброшен как дубль;
 * отдельное решение — перезаписывать ли из-за него системный буфер.
 */
internal enum class IncomingClipboardAction {

    /** Пакет игнорируется полностью (дубль доставки). */
    IGNORE,

    /** Сохранить в историю, системный буфер не трогать. */
    SAVE_ONLY,

    /** Сохранить в историю и вставить в системный буфер. */
    SAVE_AND_INSERT,
}
